async function logout() {
  await refreshQueue();
  const wait = S.queue.filter(q => q.status !== 'rejected').length;
  const ask = wait
    ? `На телефоне ${wait} неотправленных фото. Они останутся и уйдут после следующего входа. Выйти?`
    : 'Выйти из приложения? Для входа понадобятся логин и пароль.';
  if (!confirm(ask)) return;
  const t = Auth.token;
  Auth.clear();
  try { localStorage.removeItem('zf-push'); } catch (_) {}
  try {     // этот телефон больше не получает уведомления прежнего пользователя
    const reg = 'serviceWorker' in navigator ? await navigator.serviceWorker.getRegistration() : null;
    const sub = reg && reg.pushManager ? await reg.pushManager.getSubscription() : null;
    if (sub) await sub.unsubscribe();
  } catch (_) {}
  try { await fetch(API_BASE + '/photo/auth/logout', { method: 'POST', headers: { 'Authorization': 'Bearer ' + t } }); } catch (_) {}
  try { await DB.del('cache', 'tasks'); } catch (_) {}
  S.tasks = null; S.task = {};
  showLogin();
}
// язык: выбранный до входа на этом телефоне переносится в профиль, иначе берётся из профиля
let langPickedBeforeLogin = false;
function applyProfileLang() {
  const u = Auth.user; if (!u) return;
  if (langPickedBeforeLogin) { langPickedBeforeLogin = false; if (u.lang !== I18N.lang) saveLang(I18N.lang); return; }
  if (u.lang && u.lang !== I18N.lang) I18N.set(u.lang);
}
async function saveLang(l) {
  try { const r = await api('/photo/auth/lang', { method: 'POST', body: { lang: l } }); if (r.user) Auth.save(Auth.token, r.user); }
  catch (e) { if (!e.offline) toast(e.message); }
}
I18N.onChange((l, byUser) => {
  if (!byUser) return;
  if (!Auth.token) { langPickedBeforeLogin = true; return; }
  saveLang(l);
});
// проверка входа при запуске: заблокированного или чужого пользователя — на экран входа
async function checkMe() {
  if (!Auth.token) return;
  try {
    const d = await api('/photo/auth/me?scope=pwa');
    if (d.user) { Auth.save(Auth.token, d.user); applyProfileLang(); }
  } catch (e) {
    if (e.status === 403) { Auth.clear(); showLogin(e.message); }
  }
}

