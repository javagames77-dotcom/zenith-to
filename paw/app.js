// ─── Язык интерфейса: украинский / русский ───────────────
// Экраны написаны по-русски, логика не трогается. Этот модуль после каждой отрисовки
// подменяет русские надписи украинскими по словарю (I18N_UK) и правилам с числами (I18N_RX).
// Данные (названия товаров, артикулы, имена) не переводятся: их нет в словаре.
// Выбор языка: профиль пользователя (сервер), до входа — последний выбор на этом устройстве.
const I18N = (() => {
  const KEY = 'zf_lang';
  let lang = 'uk';
  try { lang = localStorage.getItem(KEY) === 'ru' ? 'ru' : 'uk'; } catch (_) {}
  const ATTRS = ['title', 'aria-label', 'placeholder', 'alt'];
  const SKIP = 'script,style,textarea,.mono,[data-noi18n]';
  const misses = new Set();                    // для проверки: русский текст без перевода

  const plUk = (n, a, b, c) => { n = Math.abs(n) % 100; const d = n % 10; if (n > 10 && n < 20) return c; if (d > 1 && d < 5) return b; if (d === 1) return a; return c; };
  function one(s) {
    if (Object.prototype.hasOwnProperty.call(I18N_UK, s)) return I18N_UK[s];
    for (const [re, fn] of I18N_RX) { const m = s.match(re); if (m) return fn(m, plUk); }
    return null;
  }
  // перевод одной строки: целиком, иначе по частям через « · », иначе как есть
  function tr(s) {
    if (s == null) return s;
    const str = String(s);
    if (!/[А-Яа-яЁё]/.test(str)) return str;
    const lead = str.match(/^\s*/)[0], tail = str.match(/\s*$/)[0];
    const core = str.trim();
    let out = one(core);
    if (out === null && core.includes(' · ')) {
      let hit = false;
      const parts = core.split(' · ').map(p => { const t = one(p.trim()); if (t !== null) hit = true; return t === null ? p : t; });
      if (hit) out = parts.join(' · ');
    }
    if (out === null) { misses.add(core); return str; }
    return lead + out + tail;
  }
  const t = s => lang === 'uk' ? tr(s) : s;

  // ── применение к странице ──
  function textNode(n) {
    if (!n.parentElement || n.parentElement.closest(SKIP)) return;
    if (n.__tr !== undefined && n.nodeValue === n.__tr) { /* наш перевод — источник прежний */ }
    else n.__ru = n.nodeValue;
    const want = lang === 'uk' ? tr(n.__ru) : n.__ru;
    n.__tr = want;
    if (n.nodeValue !== want) n.nodeValue = want;
  }
  function element(el) {
    if (el.closest && el.closest(SKIP)) return;
    el.__ruA = el.__ruA || {};
    for (const a of ATTRS) {
      if (!el.hasAttribute(a)) continue;
      const v = el.getAttribute(a);
      if (!(el.__trA && el.__trA[a] === v)) el.__ruA[a] = v;
      const want = lang === 'uk' ? tr(el.__ruA[a]) : el.__ruA[a];
      (el.__trA = el.__trA || {})[a] = want;
      if (v !== want) el.setAttribute(a, want);
    }
  }
  function walk(root) {
    if (root.nodeType === 3) return textNode(root);
    if (root.nodeType !== 1) return;
    if (root.matches && root.matches('script,style')) return;
    element(root);
    const w = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
    let n; while ((n = w.nextNode())) { if (n.nodeType === 3) { if (/\S/.test(n.nodeValue)) textNode(n); } else element(n); }
  }
  let busy = false;
  const mo = new MutationObserver(list => {
    if (busy) return; busy = true;
    try {
      for (const m of list) {
        if (m.type === 'characterData') textNode(m.target);
        else if (m.type === 'attributes') element(m.target);
        else m.addedNodes.forEach(walk);
      }
    } finally { mo.takeRecords(); busy = false; }
  });
  function start() {
    document.documentElement.lang = lang;
    walk(document.documentElement);
    mo.observe(document.documentElement, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRS });
    drawSwitches();
  }
  // окна подтверждения тоже на нужном языке
  const _confirm = window.confirm.bind(window), _alert = window.alert.bind(window);
  window.confirm = m => _confirm(t(m));
  window.alert = m => _alert(t(m));

  // ── переключатель «УКР / РУС» ──
  const listeners = [];
  function drawSwitches() {
    document.querySelectorAll('[data-lang-switch]').forEach(box => {
      box.innerHTML = ['uk', 'ru'].map(l => `<button type="button" data-l="${l}" class="${l === lang ? 'on' : ''}" aria-pressed="${l === lang}">${l === 'uk' ? 'УКР' : 'РУС'}</button>`).join('');
      box.querySelectorAll('[data-l]').forEach(b => b.onclick = () => set(b.dataset.l, true));
    });
  }
  function set(l, byUser) {
    l = l === 'ru' ? 'ru' : 'uk';
    const changed = l !== lang;
    lang = l;
    try { localStorage.setItem(KEY, l); } catch (_) {}
    document.documentElement.lang = l;
    busy = true;
    try { walk(document.documentElement); } finally { mo.takeRecords(); busy = false; }
    drawSwitches();
    if (changed || byUser) listeners.forEach(fn => { try { fn(l, byUser); } catch (_) {} });
  }
  return {
    get lang() { return lang; },
    locale() { return lang === 'uk' ? 'uk-UA' : 'ru-RU'; },
    t, tr, set, start, misses,
    onChange(fn) { listeners.push(fn); },
    drawSwitches
  };
})();


