    if (this.y0 === null) return;
    this.dy = e.touches[0].clientY - this.y0;
    if (window.scrollY > 0) { this.reset(); return; }
    if (this.dy <= 0) { if (this.el) this.el.style.opacity = 0; return; }   // палец ещё не пошёл вниз — ждём
